// Bundles js/worker.js and the modules it imports into one classic script,
// js/worker.bundle.js, so the worker has no imports of its own. (Safari does
// not serve a dedicated worker's module imports from the service worker
// cache, which breaks scoring off the main thread when offline.)
//
//   node scripts/build-worker.mjs           write js/worker.bundle.js
//   node scripts/build-worker.mjs --check   exit 1 if it is out of date
//
// Each module is wrapped in a function scope; `import { a, b } from './x.js'`
// becomes `const { a, b } = __x;` and `export` keywords are dropped.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const jsDir = join(root, 'js');
export const BUNDLE_PATH = join(jsDir, 'worker.bundle.js');

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.js';\s*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

export async function buildWorkerBundle() {
  const order = [];
  const seen = new Set();
  const sources = new Map();

  async function visit(name) {
    if (seen.has(name)) return;
    seen.add(name);
    const src = await readFile(join(jsDir, `${name}.js`), 'utf8');
    sources.set(name, src);
    for (const [, , dep] of src.matchAll(IMPORT_RE)) await visit(dep);
    order.push(name);
  }
  await visit('worker');

  const ident = (name) => `__${name.replace(/\W/g, '_')}`;
  const parts = [
    [
      '// GENERATED by scripts/build-worker.mjs from js/worker.js and its imports.',
      '// Do not edit; run `npm run build` after changing those files.',
      "'use strict';",
    ].join('\n'),
  ];
  for (const name of order) {
    let src = sources.get(name);
    const exports = [...src.matchAll(EXPORT_RE)].map((m) => m[1]);
    src = src.replace(IMPORT_RE, (_, names, dep) => `const {${names}} = ${ident(dep)};`);
    if (/^\s*import\s/m.test(src)) throw new Error(`${name}.js has an import the bundler does not understand`);
    src = src.replace(/^export\s+/gm, '');
    if (/^\s*export\s/m.test(src)) throw new Error(`${name}.js has an export the bundler does not understand`);
    const body = src.trim();
    if (name === 'worker') parts.push(`(() => {\n${body}\n})();`);
    else parts.push(`const ${ident(name)} = (() => {\n${body}\nreturn { ${exports.join(', ')} };\n})();`);
  }
  return parts.join('\n\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bundle = await buildWorkerBundle();
  if (process.argv.includes('--check')) {
    const current = await readFile(BUNDLE_PATH, 'utf8').catch(() => '');
    if (current !== bundle) {
      console.error('js/worker.bundle.js is out of date: run `npm run build`.');
      process.exit(1);
    }
    console.log('js/worker.bundle.js is up to date.');
  } else {
    await writeFile(BUNDLE_PATH, bundle);
    console.log(`Wrote js/worker.bundle.js (${bundle.length.toLocaleString('en-US')} bytes)`);
  }
}
